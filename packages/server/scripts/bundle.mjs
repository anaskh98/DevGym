/**
 * Bundles the MCP server into one file inside the plugin.
 *
 * Claude Code copies only packages/plugin when someone installs the plugin,
 * so the server has to live there, with no node_modules to install. The
 * bundle is committed; `--check` fails if it is out of date.
 */
import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const entry = resolve(here, "../src/mcp/main.ts");
const outfile = resolve(here, "../../plugin/dist/server.mjs");
const check = process.argv.includes("--check");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  write: false,
  legalComments: "none",
  // Some dependencies still call require(); give the ESM bundle one.
  banner: {
    js: [
      "// Generated by packages/server/scripts/bundle.mjs. Do not edit.",
      "import { createRequire as __ftcCreateRequire } from 'node:module';",
      "const require = __ftcCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});

const output = result.outputFiles[0];
if (!output) throw new Error("esbuild produced no output");

if (check) {
  const current = await readFile(outfile, "utf8").catch(() => null);
  if (current !== output.text) {
    console.error("packages/plugin/dist/server.mjs is out of date. Run: pnpm plugin:bundle");
    process.exit(1);
  }
  console.log("plugin bundle is up to date");
} else {
  await mkdir(dirname(outfile), { recursive: true });
  await writeFile(outfile, output.text);
  console.log(`bundled ${outfile} (${(output.text.length / 1024).toFixed(0)} kB)`);
}
